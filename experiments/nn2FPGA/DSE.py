#!/usr/bin/env python3
"""
Design-space exploration (DSE) for FIFO depths with LightningSim.

Refined flow
------------
0) Build the trace via Runner and evaluate the *current* (given) design: latency and FIFO memory.
1) Inflate: load per-FIFO depths from a text file and apply them (acts as our "oversized" reference).
2) Global shrink: reduce *all* FIFO depths together using a single scale factor (binary search)
   while keeping latency <= Phase-1 latency (from the file-based config).
3) Per-FIFO refine: for each FIFO, binary-search its own minimum depth while preserving
   the same latency target.

Notes
-----
- Deadlocks are treated as infinite latency and rejected.
- The depth file format is one mapping per line:
      <fifo_name_or_id> <depth_integer>
  Unknown names/IDs are warned and ignored; unspecified FIFOs keep the depth from
  the starting configuration for that phase.
- A CSV trace of (time, FIFO bytes) is saved to fifo_memory_trace.csv.
"""

from __future__ import annotations

import argparse
import asyncio
import dataclasses
import logging
import math
import re
import sys
import time
import csv
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Tuple

from lightningsim.model import Solution
from lightningsim.runner import Runner, RunnerStep

# --------------------------- Utilities & Types ---------------------------

@dataclasses.dataclass(frozen=True)
class DSEConfig:
    solution_path: Path
    depths_file: Path                 # Phase-1 per-FIFO depths source
    max_scale_iters: int = 20         # Iterations for global scale binary search


def setup_logging() -> None:
    console_handler = logging.StreamHandler()
    file_handler = logging.FileHandler("DSE.log", mode="w")

    console_handler.setLevel(logging.INFO)
    file_handler.setLevel(logging.INFO)

    formatter = logging.Formatter("%(asctime)s - %(levelname)s - %(message)s")
    console_handler.setFormatter(formatter)
    file_handler.setFormatter(formatter)

    logging.basicConfig(level=logging.INFO, handlers=[console_handler, file_handler])


def fifo_ids_in_order(trace) -> List[str]:
    """Return FIFO ids in a stable order (trace order)."""
    return [f.id for f in trace.fifos]


def pretty_bytes(n: int) -> str:
    return f"{n:,d} bytes"


def evaluate_fifo_memory(trace, fifo_depths: Dict[str, Optional[int]]) -> int:
    """Compute total FIFO memory usage in bytes given depths (None=∞ → ignored)."""
    total = 0
    for fifo in trace.fifos:
        d = fifo_depths.get(fifo.id, None)
        if d is None:
            continue
        width_bytes = math.ceil(fifo.width / 8)
        total += d * width_bytes
    return total


def replace_depths(params, new_depths: Dict[str, Optional[int]]):
    """dataclasses.replace wrapper for params.fifo_depths."""
    return dataclasses.replace(params, fifo_depths=dict(new_depths))


def run_latency(trace, params) -> Tuple[int, bool]:
    """Run compiled simulation with given params. Returns (latency, deadlock_flag)."""
    try:
        sim = trace.compiled.execute(params)
        return sim.top_module.end, False
    except ValueError:
        return math.inf, True


def save_memory_trace_csv(mem_trace, start_bytes: int, output_path: Path = Path("fifo_memory_trace.csv")) -> None:
    """Save the memory trace (time vs FIFO bytes) to a CSV file."""
    if not mem_trace:
        logging.warning("No memory trace recorded — nothing to save.")
        return

    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["# FIFO memory trace generated by per_fifo_minimize"])
        writer.writerow(["# Baseline_bytes", start_bytes])
        writer.writerow(["Time_seconds", "FIFO_memory_bytes"])
        for t, b in mem_trace:
            writer.writerow([f"{t:.6f}", b])

    logging.info("Saved memory trace to %s (%d samples)", output_path, len(mem_trace))


# --------------------------- Depth file I/O ---------------------------

def load_fifo_depths_from_file(trace, file_path: Path, base_depths: Optional[Dict[str, int]] = None) -> Dict[str, int]:
    """
    Read FIFO depths from a text file with lines formatted as:
        fifo_name_or_id depth

    - Unknown FIFO names/IDs are reported and ignored.
    - FIFOs not listed in the file keep their original depth (from base_depths or trace.params).
    """
    if not file_path.exists():
        raise FileNotFoundError(f"Depth file not found: {file_path}")

    base = dict(base_depths or trace.params.fifo_depths)
    base_inflated = dict()
    for k, v in base.items():
       base_inflated[k] = 1000
    base = base_inflated

    # Maps for lookup by FIFO id or name
    fifo_id_map = {f.id: f.id for f in trace.fifos}
    fifo_name_map = {f.name: f.id for f in trace.fifos if f.name}

    overrides: Dict[str, int] = {}
    with open(file_path, "r", encoding="utf-8") as f:
        for line_num, line in enumerate(f, 1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split(',')
            if len(parts) != 2:
                logging.warning(
                    "Skipping malformed line %d: %r (expected 'fifo_name,depth')",
                    line_num, line,
                )
                continue

            name, depth_str = parts
            try:
                depth = int(depth_str)
            except ValueError:
                logging.warning("Line %d: invalid depth %r", line_num, depth_str)
                continue

            # Look up FIFO by name first, then by ID
            fid = fifo_name_map.get(name)
            if fid is None:
                # Try to match the prefix removing the underscore and digits at the end
                prefix_name = re.sub(r'_\d+$', '', name)

                # Find all FIFO names containing the prefix
                matches = [
                    fifo_id
                    for fifo_name, fifo_id in fifo_name_map.items()
                    if fifo_name.startswith(prefix_name)
                ]

                if len(matches) == 1:
                    fid = matches[0]
                    logging.info(
                        "Line %d: FIFO %r not found exactly; matched by prefix %r.",
                        line_num, name, prefix_name
                    )
                else:
                    if len(matches) == 0:
                        logging.warning(
                            "Line %d: FIFO %r not found in design (prefix %r not found); skipping.",
                            line_num, name, prefix_name
                        )
                    else:
                        logging.warning(
                            "Line %d: FIFO %r matched multiple FIFOs by prefix %r (%d matches); skipping.",
                            line_num, name, prefix_name, len(matches)
                        )
                        exit(1)
                    continue

            overrides[fid] = max(1, depth)

    updated_depths = dict(base)
    updated_depths.update(overrides)

    logging.info(
        "Loaded %d FIFO depth overrides from %s (total %d FIFOs kept)",
        len(overrides), file_path, len(updated_depths),
    )
    return updated_depths


def print_current_fifo_depths(trace) -> None:
    """Print all FIFO names/IDs with their current depths and widths."""
    depths = trace.params.fifo_depths
    print("\n=== Current FIFO Depths ===")
    header = f"{'Name':30} {'ID':25} {'Depth':>10} {'Width (bits)':>15}"
    print(header)
    print("-" * len(header))
    for fifo in trace.fifos:
        d = depths.get(fifo.id, None)
        d_str = "∞" if d is None else str(d)
        print(f"{(fifo.name or '-'):30} {fifo.id:25} {d_str:>10} {fifo.width:>15}")
    print("=" * len(header))


# --------------------------- Phase 2: Global shrink ---------------------------

def global_scale_shrink(
    trace,
    start_depths: Dict[str, int],
    latency_target: int,
    max_iters: int,
) -> Dict[str, int]:
    """
    Reduce *all* finite FIFO depths together using a single scale factor s in (0,1].
    We binary-search s to keep latency <= latency_target.
    Depth update: d' = max(1, ceil(s * d)).

    Returns the new depths dict.
    """
    lo, hi = 0.0, 1.0
    best_depths = dict(start_depths)
    best_seen = 1.0

    def scaled_depths(s: float) -> Dict[str, int]:
        out: Dict[str, int] = {}
        for fid, d in start_depths.items():
            out[fid] = max(1, math.ceil(s * d))
        return out

    for it in range(max_iters):
        mid = (lo + hi) / 2.0
        trial_depths = scaled_depths(mid)
        trial_params = replace_depths(trace.params, trial_depths)
        lat, dead = run_latency(trace, trial_params)
        logging.debug(
            "[GlobalShrink] iter=%d s=%.6f  latency=%s",
            it, mid, "DEADLOCK" if dead else f"{lat:,d}"
        )

        if (not dead) and (lat <= latency_target):
            best_depths = trial_depths
            best_seen = mid
            hi = mid
        else:
            lo = mid

        if hi - lo < 1e-6:
            break

    logging.info("[GlobalShrink] Best common scale s≈%.6f", best_seen)
    return best_depths


# --------------------------- Phase 3: Per-FIFO refine ---------------------------

def per_fifo_minimize(
    trace,
    base_depths: Dict[str, int],
    latency_target: int,
    start_bytes: int,
    fifo_widths: Optional[Dict[str, int]] = None,
    time_limit: float = 1800.0,   # seconds
) -> Tuple[Dict[str, int], Optional[float], float, list[tuple[float, int]]]:
    """
    Round-robin per-FIFO bisection with time limit and progress prints.

    If `fifo_widths` is provided and `trace.compiled.dse` is available,
    feasibility checks are batched per pass via the compiled multi-core DSE engine;
    otherwise, we fall back to single-eval checks.

    Returns:
        depths: Dict[fifo_id, int] minimized depths
        t_to_start: Optional[float] seconds to first reach baseline memory
        t_total: float total seconds to finish (or time limit reached)
        mem_trace: list[(time, bytes)]
    """
    depths = dict(base_depths)
    order = [f.id for f in trace.fifos]
    lo: Dict[str, int] = {fid: 1 for fid in order}
    hi: Dict[str, int] = {fid: depths[fid] for fid in order}
    mem_trace: list[tuple[float, int]] = []

    t0 = time.perf_counter()
    t_to_start: Optional[float] = None

    cur_bytes = evaluate_fifo_memory(trace, depths)
    if cur_bytes <= start_bytes:
        t_to_start = 0.0

    def feasible_with(fid: str, trial_depth: int) -> Tuple[bool, int]:
        trial = dict(depths)
        trial[fid] = trial_depth
        params = replace_depths(trace.params, trial)
        lat, dead = run_latency(trace, params)
        return (not dead) and (lat <= latency_target), lat

    pass_idx = 0
    last_progress_time = 0.0

    logging.info("[RefineRR] Starting per-FIFO refinement (limit %.1f s)...", time_limit)

    use_batched = fifo_widths is not None and hasattr(getattr(trace, "compiled", None), "dse")
    use_batched = False
    if use_batched:
        logging.info("[RefineRR] Using compiled.dse for batched feasibility checks.")

    while True:
        elapsed = time.perf_counter() - t0
        if elapsed >= time_limit:
            logging.warning("[RefineRR] Time limit reached (%.1fs) — stopping refinement.", elapsed)
            break

        pass_idx += 1
        changed_this_pass = False

        # -------- Batched evaluation path (one DSE call per pass) --------
        evaluated_fids: set[str] = set()
        if use_batched:
            candidate_maps: list[Dict[str, int]] = []
            candidate_keys: list[str] = []
            for fid in order:
                if lo[fid] >= hi[fid]:
                    continue
                mid = (lo[fid] + hi[fid]) // 2
                trial = dict(depths)
                trial[fid] = mid
                candidate_maps.append(trial)
                candidate_keys.append(fid)

            logging.info(candidate_maps)
            exit(0)
            if candidate_maps:
                try:
                    results = trace.compiled.dse(trace.params, candidate_maps)
                except Exception as e:
                    logging.warning("[RefineRR] compiled.dse failed (%s); falling back to scalar evals.", e)
                    use_batched = False
                    results = []

                if use_batched:
                    for idx, fid in enumerate(candidate_keys):
                        evaluated_fids.add(fid)
                        r = results[idx]

                        # Try to interpret common result shapes:
                        lat = r.latency
                        dead = r is None

                        trial_depth = candidate_maps[idx][fid]
                        if (dead is False) and (lat is not None) and (lat <= latency_target):
                            hi[fid] = trial_depth
                            depths[fid] = trial_depth
                            changed_this_pass = True
                        else:
                            lo[fid] = trial_depth + 1

                        mem_now = evaluate_fifo_memory(trace, depths)
                        mem_trace.append((time.perf_counter() - t0, mem_now))
                        logging.info(f"[RefineRR] mem now {pretty_bytes(mem_now)}, start mem {pretty_bytes(start_bytes)}")
                        if t_to_start is None and mem_now <= start_bytes:
                            t_to_start = time.perf_counter() - t0
                            logging.info("[RefineRR] Reached baseline memory (%s) at pass %d.",
                                         pretty_bytes(start_bytes), pass_idx)

        # -------- Scalar fallback/continuation for any not-yet-evaluated FIFOs --------
        for fid in order:
            if lo[fid] >= hi[fid]:
                continue
            if use_batched and fid in evaluated_fids:
                continue

            elapsed = time.perf_counter() - t0
            if elapsed >= time_limit:
                logging.warning("[RefineRR] Time limit reached mid-pass — aborting.")
                break

            mid = (lo[fid] + hi[fid]) // 2
            ok, lat = feasible_with(fid, mid)

            if ok:
                hi[fid] = mid
                depths[fid] = mid
                changed_this_pass = True
            else:
                lo[fid] = mid + 1

            mem_now = evaluate_fifo_memory(trace, depths)
            mem_trace.append((time.perf_counter() - t0, mem_now))

            if t_to_start is None and mem_now <= start_bytes:
                t_to_start = time.perf_counter() - t0
                logging.info("[RefineRR] Reached baseline memory (%s) at pass %d.",
                             pretty_bytes(start_bytes), pass_idx)

        # Periodic progress log
        if (time.perf_counter() - last_progress_time) > 10.0:
            done_count = sum(1 for f in order if lo[f] >= hi[f])
            mem_now = evaluate_fifo_memory(trace, depths)
            logging.info("[RefineRR] pass=%d done=%d/%d  mem=%s  elapsed=%.1fs",
                         pass_idx, done_count, len(order), pretty_bytes(mem_now), elapsed)
            last_progress_time = time.perf_counter()

        all_done = all(lo[fid] >= hi[fid] for fid in order)
        if all_done:
            logging.info("[RefineRR] All FIFOs converged at pass %d.", pass_idx)
            break

        if not changed_this_pass:
            logging.info("[RefineRR] No changes in pass %d — convergence plateau.", pass_idx)
            for fid in order:
                depths[fid] = hi[fid]
            break

    # finalize depths to hi (best feasible)
    for fid in order:
        depths[fid] = hi[fid]

    t_total = time.perf_counter() - t0
    cur_bytes = evaluate_fifo_memory(trace, depths)

    logging.info("[RefineRR] Finished in %.2fs; final memory %s", t_total, pretty_bytes(cur_bytes))
    if t_to_start is not None:
        logging.info("[RefineRR] Time to reach baseline memory: %.2fs", t_to_start)
    else:
        logging.info("[RefineRR] Baseline memory was never reached.")

    return depths, t_to_start, t_total, mem_trace


def print_module_tree(module, indent: str = "", max_digits: Optional[int] = None) -> None:
    if max_digits is None:
        max_digits = len(f"{module.end:,d}")
    print(f"[{module.start:{max_digits},d}-{module.end:{max_digits},d}] {indent}{module.name}")
    for sub in module.submodules:
        print_module_tree(sub, indent + "    ", max_digits)


async def build_trace(solution_path: Path):
    solution = Solution(solution_path.resolve())
    runner = Runner(solution)

    runner.steps[RunnerStep.ANALYZING_PROJECT].on_start(lambda _: logging.info("Analyzing project..."))
    runner.steps[RunnerStep.WAITING_FOR_BITCODE].on_start(lambda _: logging.info("Waiting for bitcode..."))
    runner.steps[RunnerStep.GENERATING_SUPPORT_CODE].on_start(lambda _: logging.info("Generating support code..."))
    runner.steps[RunnerStep.LINKING_BITCODE].on_start(lambda _: logging.info("Linking bitcode..."))
    runner.steps[RunnerStep.COMPILING_BITCODE].on_start(lambda _: logging.info("Compiling bitcode..."))
    runner.steps[RunnerStep.LINKING_TESTBENCH].on_start(lambda _: logging.info("Linking testbench..."))
    runner.steps[RunnerStep.RUNNING_TESTBENCH].on_start(lambda _: logging.info("Running testbench..."))
    runner.steps[RunnerStep.PARSING_SCHEDULE_DATA].on_start(lambda _: logging.info("Parsing schedule data..."))
    runner.steps[RunnerStep.RESOLVING_TRACE].on_start(lambda _: logging.info("Resolving dynamic schedule..."))

    trace = await runner.run()
    logging.info("Trace ready: %d FIFOs, %d AXI interfaces", len(trace.fifos), len(trace.axi_interfaces))
    return trace


# --------------------------- Main flow ---------------------------

async def async_main(cfg: DSEConfig) -> int:
    trace = await build_trace(cfg.solution_path)

    # Phase 0: evaluate current design (given point)
    base_params = trace.params
    base_lat, base_dead = run_latency(trace, base_params)
    if base_dead:
        logging.warning("Baseline (original) configuration deadlocks.")
    else:
        logging.info("Baseline latency: %s cycles", f"{base_lat:,d}")

    start_bytes = evaluate_fifo_memory(trace, base_params.fifo_depths)
    logging.info("Baseline FIFO memory: %s", pretty_bytes(start_bytes))

    # Phase 1: inflate from depths file (acts as our reference configuration)
    file_depths = load_fifo_depths_from_file(trace, cfg.depths_file, base_depths=base_params.fifo_depths)
    file_params = replace_depths(base_params, file_depths)
    file_lat, dead = run_latency(trace, file_params)
    if dead:
        logging.error("Deadlock with file-based depths from %s; cannot proceed.", cfg.depths_file)
        return 2

    print()  # spacer
    logging.info("[Phase 1] Applied depths from %s → latency %s cycles", cfg.depths_file, f"{file_lat:,d}")

    # Optionally, show the module tree once (best-effort)
    try:
        sim = trace.compiled.execute(file_params)
        # print_module_tree(sim.top_module)
    except Exception:
        pass

    # Phase 2: global shrink (scale all together)
    print()
    logging.info("[Phase 2] Global shrink (common scale) targeting latency ≤ %s", f"{file_lat:,d}")

    t0 = time.perf_counter()
    scaled_depths = global_scale_shrink(
        trace=trace,
        start_depths=file_depths,
        latency_target=file_lat,
        max_iters=cfg.max_scale_iters,
    )
    t1 = time.perf_counter()

    scaled_params = replace_depths(base_params, scaled_depths)
    scaled_bytes = evaluate_fifo_memory(trace, scaled_depths)
    lat_after_scale, _ = run_latency(trace, scaled_params)
    logging.info("[Phase 2] Done in %.2fs → memory %s, latency %s cycles",
                 (t1 - t0), pretty_bytes(scaled_bytes), f"{lat_after_scale:,d}")

    # Prepare widths once for compiled.dse batching (type matches fifo.id as exposed by trace)
    fifo_widths: Dict[str, int] = {fifo.id: fifo.width for fifo in trace.fifos}

    # Phase 3: per-FIFO refine to minima (batched where possible)
    print()
    logging.info("[Phase 3] Per-FIFO refinement (binary search) with target latency ≤ %s", f"{file_lat:,d}")
    refined_depths, t_to_start, t_total, mem_trace = per_fifo_minimize(
        trace=trace,
        base_depths=scaled_depths,
        latency_target=file_lat,
        start_bytes=start_bytes,  # track how fast we beat the original memory
        fifo_widths=fifo_widths,  # batched feasibility checks via compiled.dse
    )
    refined_params = replace_depths(base_params, refined_depths)
    refined_bytes = evaluate_fifo_memory(trace, refined_depths)
    final_lat, final_dead = run_latency(trace, refined_params)
    if final_dead:
        logging.error("[Phase 3] Unexpected deadlock at refined solution.")
        return 3

    if t_to_start is not None:
        logging.info("[Phase 3] Time to reach starting FIFO memory: %.2fs", t_to_start)
    else:
        logging.info("[Phase 3] Never reached starting FIFO memory during refinement.")

    logging.info("[Phase 3] Time to reach per-FIFO minimum: %.2fs", t_total)
    logging.info("Final latency: %s cycles", f"{final_lat:,d}")
    logging.info("FIFO memory: start %s → final %s (Δ %s)",
                 pretty_bytes(start_bytes),
                 pretty_bytes(refined_bytes),
                 pretty_bytes(refined_bytes - start_bytes))

    # Print final FIFO depths
    print("\nFinal FIFO depths:")
    for f in trace.fifos:
        print(f"  {f.name or f.id}: {refined_depths[f.id]}")
    
    with open("final_fifo_depths.csv", "w", encoding="utf-8") as f:
        for fobj in trace.fifos:
            f.write(f"{fobj.name or fobj.id},{refined_depths[fobj.id]}\n")

    save_memory_trace_csv(mem_trace, start_bytes)
    return 0


def parse_args(argv: Iterable[str]) -> DSEConfig:
    p = argparse.ArgumentParser(description="FIFO-depth DSE with LightningSim (depths from file).")
    p.add_argument(
        "--solution",
        type=Path,
        default=Path("./test_lightning/solution1"),
        help="Path to Vitis HLS solution directory (default: ./test_lightning/solution1)",
    )
    p.add_argument(
        "--depths-file",
        type=Path,
        default=Path("fifo_depths.txt"),
        help="Text file mapping 'fifo_name_or_id depth' used for Phase 1",
    )
    p.add_argument(
        "--scale-iters",
        type=int,
        default=20,
        help="Max iterations for global scale binary search (default: 20)",
    )
    args = p.parse_args(list(argv))
    return DSEConfig(
        solution_path=args.solution,
        depths_file=args.depths_file,
        max_scale_iters=args.scale_iters,
    )


def main() -> int:
    cfg = parse_args(sys.argv[1:])
    setup_logging()
    try:
        return asyncio.run(async_main(cfg))
    except KeyboardInterrupt:
        logging.warning("Interrupted.")
        return 130


if __name__ == "__main__":
    sys.exit(main())
